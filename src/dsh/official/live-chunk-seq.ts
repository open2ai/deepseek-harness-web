// 实时增量帧的合成序号（适配上游 0.1.7-rc.2）：镜像上游给瞬态增量帧赋序号的规则。
//
// ⚠️ CORE-COUPLED（核心耦合；目录名 official，本仓库注释里称"核心"）——只映射 dsh 核心规则，
// 勿混入插件自有逻辑；核心变化只改本目录。

/**
 * 给**没有持久序号**的实时增量帧算一个合成序号：落在「当前持久游标之后、下一条持久事件之前」。
 *
 * 为什么需要：帧本身不带序号，与持久事件同处一个数组时排序里就没有位置 —— 按 0 排会跑到最前
 * （行序颠倒：回答先于提问建行），一律排最后则与「帧到达之后才产生的持久事件」次序相反。
 * 合成序号让每帧锚在**它到达那一刻**的持久事件之后，与上游对合成锚点的处理同一口径。
 *
 * @param durableSeq - 已收到的**持久**事件的最大序号（**不含**合成序号）；一条都没有时 -1
 * @param transientInGap - 距上一条持久事件以来已发出的帧数（本条**先自增**再传入，与上游同序）
 */
export function liveChunkSeq(durableSeq: number, transientInGap: number): number {
    return durableSeq + 1 - 1 / (transientInGap + 1);
}
