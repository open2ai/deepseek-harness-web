// 分叉子会话的**标题升号**（纯函数、零依赖）。
//
// 上游流程（客户端三步，不是服务端能力）：
//   ① 决定升号时，先读**源会话的持久标题**；
//   ② 调服务端分叉（只传会话标识与切点序号）；
//   ③ 用本函数算出新标题，再调服务端的「改名」；改名失败即视为整体失败。
//
// ⚠️ **升号在客户端做，服务端没有这个能力**（2026-10-13 查证）：
// 服务端的分叉请求类型只有两个字段 —— 会话标识与可选的切点序号，**没有**"是否升号"这类开关
//（全仓搜不到那个字段名）。插件曾把它当 **RPC 字段**发出去（服务端忽略）⇒ 子会话标题永远等于
// 源标题、**不会出现 ` (1)`**（真机："新对话名字后面没有像上游一样的命名规则"）。
//
// 为什么单独一个文件：这段要被**宿主主逻辑**用（分叉流程），也要被**守卫直接调用**断言逐例行为。
// 放在 `api/dshService.ts` 里的话，守卫一 import 就把 `vscode` 拉进来（探针环境没有它），
// 判据就只能退化成"搜源码字符串"。

/**
 * 给源标题升号（上游 `increasedForkTitle` 的逐字复刻）。
 *
 * 规则三条，**顺序即优先级**：
 *   ① 结尾是**半角** `(n)` → 换成 `(n+1)`，其余原样保留（如 `标题 (1)` → `标题 (2)`）；
 *   ② 结尾是**全角** `（n）` → 换成 `（n+1）`（保留用户的括号形态，不擅自换成半角）；
 *   ③ 都没有 → **追加** ` (1)`（注意**前导空格**）。
 *
 * 用 `BigInt` 加一而不是 `Number`：上游如此，避免极大编号的精度问题（`(9007199254740993)` 这类）。
 * 正则用 `.*?` + `$` 锚定：**只看结尾**那一个编号（`title (1) (2)` 只动最后的 `(2)`）。
 *
 * @param title - 源会话的 durable title。
 * @returns 分叉子会话应使用的标题。
 */
export function increasedForkTitle(title: string): string {
    const ascii = /^(.*?)\((\d+)\)$/u.exec(title);
    if (ascii?.[1] !== undefined && ascii[2] !== undefined) {
        return `${ascii[1]}(${BigInt(ascii[2]) + 1n})`;
    }
    const fullWidth = /^(.*?)（(\d+)）$/u.exec(title);
    if (fullWidth?.[1] !== undefined && fullWidth[2] !== undefined) {
        return `${fullWidth[1]}（${BigInt(fullWidth[2]) + 1n}）`;
    }
    return `${title} (1)`;
}
