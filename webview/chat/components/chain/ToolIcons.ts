/**
 * 该工具行用哪张**上游图形**；`undefined` = 该工具没有上游图形，工具行仍走 codicon 近似。
 *
 * 两个来源集合照上游那套归类：**起一个智能体**的工具（`subagent` / `list_subagent_models`）用
 * 「智能体预设」，**智能体之间的协调**类工具（`list_agents` / `send_message` / `interrupt_agent` /
 * `wait_agent` / `spawn_teammate`）用「双人」。两边**不是同一个图标**，别合并成一个。
 *
 * @param name - 工具行上的原始工具名。
 */
export function toolGlyphOf(name: string): unknown | undefined {
  if (name === 'subagent' || name === 'list_subagent_models') {
    return agentPreset()
  }
  if (
    name === 'list_agents' ||
    name === 'send_message' ||
    name === 'interrupt_agent' ||
    name === 'wait_agent' ||
    name === 'spawn_teammate'
  ) {
    return users()
  }
  return undefined
}
